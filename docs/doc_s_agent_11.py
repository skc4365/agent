# ## 3.6 실행 루프

# AI 에이전트는 보통 반복적인 실행 루프를 가집니다.

# 대표적인 구조는 다음과 같습니다.

# ```text
# 사용자 목표 입력
# → 현재 상태 분석
# → 다음 행동 결정
# → 도구 호출 또는 응답 생성
# → 결과 관찰
# → 결과 평가
# → 다음 행동 결정
# → 반복
# → 최종 답변
# ```

# 이를 더 간단히 표현하면 다음과 같습니다.

# ```text
# Think → Act → Observe → Think → Act → Observe → Final
# ```

# 이 루프가 에이전트의 핵심입니다.  
# 단순 LLM 호출은 한 번의 답변으로 끝나지만, 에이전트는 목표 달성까지 여러 번 판단하고 행동할 수 있습니다.

