"""11. Planning and delegation: 계획·위임

핵심 구문
TodoListMiddleware: 작업 계획 | SubAgentMiddleware: 작업 위임
researcher: 자료 조사 담당 | 주 에이전트·하위 에이전트: 동일 OpenAI 모델

실행: uv run doc_s/doc_s_agent_11.py
준비: 프로젝트 루트 .env: OPENAI_API_KEY
추가 패키지: uv add deepagents
모델 변경: create_agent의 model
"""

from pathlib import Path
from dotenv import load_dotenv
from langchain.agents import create_agent
from langchain.tools import tool
from deepagents.backends import StateBackend
from deepagents.middleware import FilesystemMiddleware
from langchain.agents.middleware import TodoListMiddleware
from deepagents.middleware.subagents import SubAgentMiddleware

# 1. 환경 설정: 프로젝트 루트 .env → OPENAI_API_KEY
load_dotenv(Path(__file__).resolve().parent.parent / ".env")

@tool
def search(query: str) -> str:
    """AI 에이전트 학습 자료 조회 — 로컬 모의 검색"""
    return (
        f"조회 질문: {query}\n"
        "에이전트는 모델이 도구를 선택하고 결과를 읽으며 작업을 수행한다. "
        "system_prompt는 행동 지침이고 response_format은 응답 구조다. "
        "checkpointer와 thread_id를 함께 사용하면 대화 이력을 유지한다."
    )

# 가상 파일: 에이전트 상태에 저장 / 실제 디스크 저장 없음
backend = StateBackend()

# =================
# 서브에이전트의 최소구성
#       name: 메인 에이전트가 서브에이전트를 호출할 때 사용할 도구(Tool)의 이름.
#       description: 메인 에이전트가 "언제 이 서브에이전트에게 일을 위임할지" 판단하는 기준(LLM 도구 설명).

# researcher = {
#     "name": "researcher",
#     "description": "AI 에이전트 학습 자료 조사 담당" }

# =================

# researcher: 역할·사용 도구 정의
researcher = {
    "name": "researcher",
    "description": "AI 에이전트 학습 자료 조사 담당",
    "system_prompt": "search로 자료를 확인하고 한국어로 요약하세요.",
    "model": "openai:gpt-5.5",
    "tools": [search],
    "middleware": [],
}

# 2. 에이전트 구성: 모델·도구·실습 옵션
agent = create_agent(
    model="openai:gpt-5.5",
    tools=[search],
    system_prompt="학습 자료는 search로 확인하고 한국어로 답하세요.",
    middleware=[
        FilesystemMiddleware(backend=backend),
        TodoListMiddleware(),
        SubAgentMiddleware(backend=backend, subagents=[researcher]),
    ],
)

# 3. 질문 실행: content 수정 → 결과 비교
result = agent.invoke(
    {"messages": [{"role": "user", "content": '할 일 목록을 작성하고 researcher에게 AI 에이전트 자료 조사를 위임한 뒤 요약해줘.'}]}
)

# 4. 결과 확인
for message in result["messages"]:
    # 메시지 흐름: 사용자 입력 → 도구 호출 → 도구 결과 → 최종 답변
    message.pretty_print()


# 결과
# - 지금 검색이 필요한가?
# - 계산이 필요한가?
# - 사용자에게 추가 질문을 해야 하는가?
# - 결과가 충분한가?
# - 다음 단계로 넘어가도 되는가?

# 계획과 추론이 약하면 에이전트는 불필요한 도구를 호출하거나, 중요한 단계를 빠뜨리거나, 잘못된 결론을 낼 수 있습니다.

