# ## 4. 주요 AI 에이전트 패턴

# ### 1) ReAct

# ReAct는 **Reasoning + Acting**의 줄임말입니다.

# 모델이 추론과 행동을 번갈아 수행하는 방식입니다.

# ```text
# Thought → Action → Observation → Thought → Action → Final Answer
# ```

# 에이전트 구조를 이해하는 데 가장 기본적인 패턴입니다.

# ### 2) Tool Use / Function Calling

# 모델이 직접 답변하지 않고 필요한 경우 외부 도구나 API를 호출하는 패턴입니다.

# 적합한 작업:

# - 실시간 정보 조회
# - 계산
# - DB 검색
# - 업무 시스템 조작
# - 파일 처리

# ### 3) RAG 결합

# RAG는 검색 기반 생성 방식입니다.

# 문서나 데이터베이스에서 관련 정보를 검색한 뒤, 그 내용을 바탕으로 답변합니다.

# 활용 예:

# - PDF 질의응답
# - 사내 문서 검색 챗봇
# - 법률 문서 분석
# - 논문 요약
# - 고객센터 지식베이스 검색

# ### 4) Multi-agent

# 여러 에이전트가 역할을 나누어 협업하는 구조입니다.

# 예시:

# - Planner Agent: 계획 수립
# - Researcher Agent: 자료 조사
# - Analyst Agent: 분석
# - Writer Agent: 보고서 작성
# - Critic Agent: 검토

# 복잡한 작업에는 유용하지만 비용과 설계 복잡도가 증가합니다.

