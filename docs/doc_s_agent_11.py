# ## 4.4 Multi-agent 패턴

# Multi-agent는 여러 에이전트가 역할을 나누어 협업하는 구조입니다.

# 예시 역할:

# - Planner Agent: 전체 계획 수립
# - Research Agent: 자료 조사
# - Coding Agent: 코드 작성
# - Critic Agent: 결과 검토
# - Executor Agent: 실제 실행
# - Summarizer Agent: 최종 요약

# 예를 들어 보고서 작성 시스템은 다음과 같이 구성할 수 있습니다.

# ```text
# 사용자 요청
# → Planner가 작업 분해
# → Researcher가 자료 조사
# → Analyst가 분석
# → Writer가 보고서 작성
# → Critic이 오류 검토
# → 최종 답변
# ```

# Multi-agent의 장점은 다음과 같습니다.

# - 복잡한 작업 분담 가능
# - 역할별 전문화 가능
# - 검토자 에이전트를 통한 품질 향상
# - 병렬 처리 가능

# 단점도 있습니다.

# - 설계 복잡도 증가
# - 에이전트 간 불필요한 대화 증가
# - 비용 증가
# - 책임 소재 불명확
# - 오류가 연쇄적으로 전파될 수 있음

