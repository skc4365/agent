# ## 3. AI 에이전트의 핵심 구성요소

# ### 1) LLM

# LLM은 에이전트의 두뇌 역할을 합니다.

# 주요 역할은 다음과 같습니다.

# - 사용자 의도 이해
# - 목표 분해
# - 다음 행동 결정
# - 도구 선택
# - 도구 호출 결과 해석
# - 최종 답변 생성

# ### 2) 도구 사용

# AI 에이전트는 외부 도구를 사용해 LLM의 한계를 보완합니다.

# 예시 도구:

# - 웹 검색
# - 계산기
# - 데이터베이스 조회
# - 파일 읽기/쓰기
# - 코드 실행
# - 이메일, 캘린더, 업무 시스템 API
# - 사내 문서 검색

# ### 3) Function Calling

# Function Calling은 모델이 정해진 형식으로 함수를 호출하게 하는 방식입니다.

# 예를 들어 사용자가 “내일 서울 날씨 알려줘”라고 하면, 모델은 날씨 API를 호출하기 위해 다음과 같은 구조화된 요청을 만들 수 있습니다.

# ```json
# {
#   "name": "get_weather",
#   "arguments": {
#     "city": "서울",
#     "date": "내일"
#   }
# }
# ```

# ### 4) 메모리

# 메모리는 에이전트가 이전 대화나 사용자 정보를 기억하게 합니다.

# 종류는 다음과 같습니다.

# - **단기 메모리**: 현재 대화의 문맥 유지
# - **장기 메모리**: 사용자 선호, 프로젝트 정보 등 저장
# - **작업 메모리**: 현재 진행 중인 작업 상태 관리

# ### 5) 계획과 추론

# 에이전트는 큰 목표를 작은 작업으로 나누고 실행 순서를 정합니다.

# 예를 들어 “경쟁사 분석 보고서 작성” 요청은 다음처럼 분해할 수 있습니다.

# 1. 경쟁사 목록 파악
# 2. 제품 조사
# 3. 가격 정책 조사
# 4. 강점과 약점 분석
# 5. 보고서 작성

# ### 6) 실행 루프

# AI 에이전트는 보통 다음과 같은 반복 루프를 가집니다.

# ```text
# Think → Act → Observe → Think → Act → Observe → Final
# ```

# 즉, 생각하고, 행동하고, 결과를 관찰한 뒤 다시 판단합니다.

