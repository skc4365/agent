# ## 4.3 RAG 결합 패턴

# RAG는 **Retrieval-Augmented Generation**의 약자입니다.  
# 즉, 검색을 통해 관련 문서를 가져온 뒤 LLM이 답변을 생성하는 방식입니다.

# 에이전트와 RAG를 결합하면 다음이 가능합니다.

# - 사내 문서 기반 질의응답
# - 논문 검색 후 요약
# - 법률 / 규정 문서 분석
# - 기술 문서 기반 지원 챗봇
# - 고객센터 지식베이스 활용

# 기본 흐름은 다음과 같습니다.

# ```text
# 사용자 질문
# → 검색 쿼리 생성
# → 벡터 DB 또는 검색 엔진에서 관련 문서 검색
# → 문서 내용 요약 및 근거 추출
# → 답변 생성
# → 필요하면 추가 검색
# ```

# RAG 결합 에이전트의 장점은 다음과 같습니다.

# - 최신 또는 사내 지식 활용 가능
# - 환각 감소
# - 출처 기반 답변 가능
# - 도메인 특화 성능 향상

# 단, 검색 품질이 낮으면 답변 품질도 낮아집니다.

