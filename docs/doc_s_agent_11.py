# # 4. 주요 에이전트 패턴

# ## 4.1 ReAct 패턴

# ReAct는 **Reasoning + Acting**의 줄임말입니다.

# 즉, 모델이 다음 두 가지를 번갈아 수행합니다.

# - Reasoning: 현재 상황을 추론한다.
# - Acting: 필요한 행동이나 도구 호출을 실행한다.

# 기본 흐름은 다음과 같습니다.

# ```text
# Thought: 무엇을 해야 하는지 생각
# Action: 도구 선택 및 실행
# Observation: 도구 결과 확인
# Thought: 결과를 바탕으로 다음 판단
# Action: 다음 행동
# Observation: 결과 확인
# Final Answer: 최종 답변
# ```

# 예시:

# ```text
# 질문: 현재 애플 주가와 최근 실적을 바탕으로 간단한 투자 의견을 알려줘.

# Thought: 최신 주가와 실적 정보가 필요하다.
# Action: 주가 조회 API 호출
# Observation: 현재 주가는 ...
# Thought: 최근 실적도 확인해야 한다.
# Action: 웹 검색 호출
# Observation: 최근 분기 실적은 ...
# Thought: 정보를 종합해 신중한 의견을 제시한다.
# Final Answer: ...
# ```

# ReAct는 에이전트 구조를 이해하는 데 가장 기본적이고 중요한 패턴입니다.

# ---

# ## 4.2 Tool Use / Function Calling 패턴

# 이 패턴은 모델이 직접 답하지 않고 필요한 경우 외부 도구를 호출하는 구조입니다.

# 적합한 작업은 다음과 같습니다.

# - 실시간 정보 조회
# - 계산
# - 데이터베이스 검색
# - 업무 시스템 조작
# - 파일 처리
# - 외부 API 호출

# 예:

# 사용자 요청:

# > 지난달 매출 데이터를 분석해서 요약해줘.

# 에이전트 흐름:

# 1. DB 조회 함수 호출
# 2. 매출 데이터 수신
# 3. 통계 계산 함수 호출
# 4. 그래프 생성 도구 호출
# 5. 요약 보고서 작성

# 이 패턴은 실제 업무 자동화 에이전트에서 매우 중요합니다.

