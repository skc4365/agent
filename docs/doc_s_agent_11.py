# ## 7. 주의점과 한계

# AI 에이전트는 강력하지만 다음 위험이 있습니다.

# - **환각**: 사실이 아닌 내용을 생성할 수 있음
# - **잘못된 도구 호출**: 부정확한 API 호출이나 인자 오류
# - **무한 루프**: 계속 도구를 호출하며 종료하지 못할 수 있음
# - **비용 증가**: 반복 호출, 긴 컨텍스트, 멀티에이전트 구조로 비용 상승
# - **보안 문제**: 프롬프트 인젝션, 민감정보 유출, 권한 오남용
# - **평가 어려움**: 최종 답변뿐 아니라 과정도 평가해야 함
# - **메모리 관리 문제**: 오래된 정보나 잘못된 사용자 정보가 남을 수 있음

