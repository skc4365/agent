# ## 2. 핵심 요약

# AI 에이전트는 단순히 답변을 생성하는 챗봇이 아니라, **목표를 이해하고 필요한 도구를 선택해 실행하며, 결과를 바탕으로 다음 행동을 결정하는 시스템**입니다.

# 즉, AI 에이전트의 핵심은 다음 구조입니다.

# > 목표 이해 → 계획 수립 → 도구 호출 → 결과 관찰 → 다음 행동 결정 → 최종 응답

# 검색 자료에서도 AI 에이전트는 **모델이 도구를 선택하고 결과를 읽으며 작업을 수행하는 구조**로 설명됩니다. 또한 `system_prompt`는 에이전트의 행동 지침, `response_format`은 응답 구조 제어, `checkpointer`와 `thread_id`는 대화 이력 유지에 활용될 수 있습니다.

